"""M6.6 — the §5.7 evidence pack, generated from a paper-run decision journal.

This proves the pack generator against real journal rows in Postgres, exactly as it will run in
production: entries are written through the real `Journal` (which stores evidence content-addressed
and reads back through the same query surface the pack uses), and the pack is then generated by
reading only those rows. The three M6.6 acceptance criteria are each proved here:

1. **A pack generates from the paper run with every §5.7 section populated.** A faithful paper-run
   journal — SIP instalments parked (A7), a tactical deployment, a T0 heartbeat every day, T1
   reviews with token spend and break-condition verdicts, an A8 `RAIL_BLOCK`, a `SKIPPED_DATA_RED`
   data-red day, and a core exit that books a realized gain — is written for the reference case, and
   `generate_pack` produces an `EvidencePack` with all seven §5.7 sections populated.

2. **Every number traces to journal entries (no separate accounting).** Each figure the pack
   attributes to the case's activity is recomputed *independently* here, straight from
   `Journal.count`/`Journal.entries`, and asserted equal to the pack's — turnover, tax events, cost
   burn, rail blocks, data-red skips, the decision verdicts, and the SIP cashflow stream that drives
   the return. The pack keeps no ledger the journal does not.

3. **The rail-breach count is a bug indicator, not a neutral metric.** The clean run's rail section
   reads CLEAN with zero breaches and its rendered text calls a breach a bug against invariant #6;
   a second case whose journal carries a breach that reached the book flips the verdict to
   BUGS_PRESENT and the render to a defect warning. `RAIL_BLOCK` lines (rails *working*) are counted
   as context, never as breaches.

The entries mirror the payloads the M5 loop's real writers emit — A7's park
(`source_SIP_INSTALMENT`/`shares`/`price`), its deploy (`deployed_inr`), and A8's block (`rails`) —
so the pack's extraction is exercised against the real journal shape, not a bespoke one. The
decision journal and evidence store are the real Postgres/lake ones, so this needs the docker
postgres (`make up`) and skips loudly if unreachable, as `test_journal.py` and
`test_paper_run_10_sessions.py` do. Time is frozen and injected; no network is touched.
"""

