# ── acceptance 1: a pack generates from the paper run with every §5.7 section populated ────────


def test_pack_generates_with_every_section_populated(pack: EvidencePack) -> None:
    """All seven §5.7 sections are present and carry real content from the paper run."""
    assert pack.case_id == CASE_ID
    assert pack.trigger is PackTrigger.GRADUATION
    assert pack.window_start == WINDOW_START and pack.window_end == WINDOW_END
    assert pack.entries_reviewed > 0

    # 1. Returns vs both benchmarks (XIRR since SIP), on two pay-ins plus the terminal mark.
    assert pack.returns.cashflow_count == 2
    assert pack.returns.first_sip_date == SIP_1
    assert pack.returns.total_invested_inr == SIP_AMOUNT * 2
    assert pack.returns.terminal_value_inr == Decimal("21500")
    # Three distinct return figures were struck (portfolio vs both benchmarks).
    assert pack.returns.portfolio_xirr != pack.returns.benchmark_xirr
    assert pack.returns.theme_xirr != pack.returns.benchmark_xirr

    # 2. Drawdown profile — a genuine peak-to-trough on the NAV marks.
    assert pack.drawdown.max_drawdown_pct > Decimal("0")
    assert pack.drawdown.peak_date == DEPLOY_DATE and pack.drawdown.trough_date == DATA_RED_DATE

    # 3. Rail breaches — present, and clean on this run.
    assert pack.rail_breaches.breach_count == 0
    assert pack.rail_breaches.rail_blocks == 1

    # 4. Decision review — T1/T2 verdicts, with the exit that followed the BROKEN one.
    assert len(pack.decision_review.reviews) == 2
    broken = [r for r in pack.decision_review.reviews if r.verdict == "BROKEN"]
    assert len(broken) == 1 and broken[0].subsequent_action == "SELL"

    # 5. Turnover + tax by sleeve — every traded sleeve, and the realized-gain tax event.
    sleeves = {s.sleeve for s in pack.turnover_tax.by_sleeve}
    assert sleeves == {Sleeve.CASH, Sleeve.TACTICAL, Sleeve.CORE}
    assert len(pack.turnover_tax.tax_events) == 1
    assert pack.turnover_tax.untraceable_trades == ()

    # 6. Token / cost burn — the two model-calling tiers.
    assert {t.actor for t in pack.cost_burn.by_tier} == {Actor.T1, Actor.T2}
    assert pack.cost_burn.total_cost_inr == T1_TOKENS.cost_inr + T2_TOKENS.cost_inr

    # 7. Data-quality skips — the one data-red day.
    assert pack.data_quality.data_red_skips == 1
    assert pack.data_quality.skipped_dates == (DATA_RED_DATE,)


# ── acceptance 2: every number traces to journal entries (no separate accounting) ─────────────────


def test_every_number_traces_to_journal_entries(pack: EvidencePack, pack_journal: Journal) -> None:
    """Each figure is recomputed from the journal and matches the pack — no second ledger."""
    window = JournalFilter(case_id=CASE_ID, start=WINDOW_START, end=WINDOW_END)

    # Rail blocks: the pack's count equals the journal's count of RAIL_BLOCK rows.
    assert pack.rail_breaches.rail_blocks == pack_journal.count(
        replace(window, decision=Decision.RAIL_BLOCK)
    )

    # Data-red skips: the pack's count equals the journal's count of SKIPPED_DATA_RED rows.
    assert pack.data_quality.data_red_skips == pack_journal.count(
        replace(window, decision=Decision.SKIPPED_DATA_RED)
    )

    # Cost burn: recomputed by summing TokenSpend over every entry that carried one.
    all_entries = pack_journal.entries(window)
    expected_cost = sum(
        (e.tokens.cost_inr for e in all_entries if e.tokens is not None), Decimal("0")
    )
    expected_in = sum(e.tokens.tokens_in for e in all_entries if e.tokens is not None)
    assert pack.cost_burn.total_cost_inr == expected_cost
    assert pack.cost_burn.total_tokens_in == expected_in

    # SIP cashflows: the invested total equals the sum of source_SIP_INSTALMENT over park entries.
    buys = pack_journal.entries(replace(window, decision=Decision.BUY))
    expected_invested = sum(
        (
            Decimal(e.payload["source_SIP_INSTALMENT"])
            for e in buys
            if "source_SIP_INSTALMENT" in e.payload
        ),
        Decimal("0"),
    )
    assert pack.returns.total_invested_inr == expected_invested

    # Turnover: TACTICAL turnover equals the deploy value read from its own journal entry.
    tactical = next(s for s in pack.turnover_tax.by_sleeve if s.sleeve is Sleeve.TACTICAL)
    (deploy_entry,) = [e for e in buys if e.isin == DEPLOY_ISIN and e.sleeve is Sleeve.TACTICAL]
    assert tactical.buy_value_inr == Decimal(deploy_entry.payload["deployed_inr"])

    # Tax event: the realized gain equals what the SELL entry itself recorded.
    sells = pack_journal.entries(replace(window, decision=Decision.SELL))
    (sell_entry,) = sells
    (tax_event,) = pack.turnover_tax.tax_events
    assert tax_event.realized_gain_inr == Decimal(sell_entry.payload["realized_gain_inr"])
    assert tax_event.isin == sell_entry.isin

    # Entries reviewed: the pack read exactly the window's journal rows, nothing else.
    assert pack.entries_reviewed == len(all_entries)


# ── acceptance 3: the rail-breach count is a bug indicator, not a neutral metric ──────────────────


def test_rail_breach_count_is_presented_as_a_bug_indicator(pack: EvidencePack) -> None:
    """A clean run reads CLEAN; the rendered text frames a breach as a bug against invariant #6."""
    assert pack.rail_breaches.is_clean
    assert pack.rail_breaches.verdict == "CLEAN"

    rendered = render_markdown(pack)
    rail_lines = rendered.lower()
    assert "target" in rail_lines and "zero" in rail_lines
    assert "bug" in rail_lines  # a breach is called a bug, not a neutral risk event
    assert "invariant #6" in rendered
    # A RAIL_BLOCK (rails working) must not be miscounted as a breach.
    assert "0 — verdict clean" in rail_lines


def test_a_breach_that_reached_the_book_flips_the_verdict_to_bug(pack_journal: Journal) -> None:
    """The second case's filled breach is surfaced as BUGS_PRESENT, with a defect warning."""
    breach_pack = generate_pack(
        pack_journal,
        case_id=BREACH_CASE_ID,
        window_start=WINDOW_START,
        window_end=WINDOW_END,
        valuation=_valuation(),
        generated_at=RUN_AT,
        trigger=PackTrigger.MONTHLY,
    )
    assert breach_pack.rail_breaches.breach_count == 1
    assert not breach_pack.rail_breaches.is_clean
    assert breach_pack.rail_breaches.verdict == "BUGS_PRESENT"

    rendered = render_markdown(breach_pack)
    assert "BUGS_PRESENT" in rendered
    assert "defect" in rendered.lower()
    assert "MAX_POSITION" in rendered  # the breached cap is named for investigation


# ── readable in ten minutes: the render carries every section, top to bottom ──────────────────────


def test_rendered_pack_is_a_single_readable_document(pack: EvidencePack) -> None:
    """render_markdown produces one document with all seven §5.7 section headers, in order."""
    rendered = render_markdown(pack)
    for heading in (
        "## 1. Returns vs benchmarks",
        "## 2. Drawdown profile",
        "## 3. Rail breaches",
        "## 4. Decision review",
        "## 5. Turnover & tax events by sleeve",
        "## 6. Token / cost burn",
        "## 7. Data-quality skips",
    ):
        assert heading in rendered, f"missing section: {heading}"
    # No unfilled template placeholders leaked into the render.
    assert "$" not in rendered
    assert CASE_ID in rendered


def test_empty_window_is_a_loud_refusal(pack_journal: Journal) -> None:
    """A window with no entries raises rather than emitting a hollow pack (CLAUDE.md: fail loud)."""
    from analyst.journal import EvidencePackError

    with pytest.raises(EvidencePackError):
        generate_pack(
            pack_journal,
            case_id=CASE_ID,
            window_start=date(2030, 1, 1),
            window_end=date(2030, 12, 31),
            valuation=_valuation(),
            generated_at=RUN_AT,
        )


