DATA_RED_DATE: Final = date(2026, 8, 20)
SIP_2: Final = date(2026, 9, 1)
RAIL_BLOCK_DATE: Final = date(2026, 9, 5)
T1_BROKEN_DATE: Final = date(2026, 9, 10)
EXIT_DATE: Final = date(2026, 9, 12)
AS_OF: Final = date(2026, 9, 30)

#: A distinct, earlier wall clock for the writes, so the run's `ts` values are unambiguous.
RUN_AT: Final = datetime(2026, 9, 30, 18, 30, tzinfo=IST)

DEPLOY_ISIN: Final = "INE100A01010"
INTACT_ISIN: Final = "INE200B01020"
RAIL_ISIN: Final = "INE300C01030"
EXIT_ISIN: Final = "INE400D01040"
