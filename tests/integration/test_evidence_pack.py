SIP_AMOUNT: Final = Decimal("10000")
DEPLOY_VALUE: Final = Decimal("10000")
EXIT_VALUE: Final = Decimal("15000")
EXIT_GAIN: Final = Decimal("3000")
EXIT_CHARGES: Final = Decimal("52.50")

T1_TOKENS: Final = TokenSpend(tokens_in=1200, tokens_out=300, cost_inr=Decimal("0.85"))
T2_TOKENS: Final = TokenSpend(tokens_in=4000, tokens_out=900, cost_inr=Decimal("2.40"))
STUB_MODEL: Final = "stub-model"


# ── valuation marks (the only non-journal inputs the pack takes) ──────────────────────────────────


def _tri(slug: str, name: str, levels: dict[date, str]) -> TriSeries:
    """A published TRI series from a date→level table."""
    return TriSeries(
        index_slug=slug,
        index_name=name,
        method="published",
        points=tuple(
            TriPoint(
                index_slug=slug,
                index_name=name,
                as_of=as_of,
                tri_value=Decimal(level),
                method="published",
            )
            for as_of, level in sorted(levels.items())
        ),
    )


def _valuation() -> PackValuation:
    """The NAV series (with a real drawdown) and the two benchmark legs.

    NAV dips from ₹1,05,000 to ₹98,000 mid-run before recovering to ₹1,10,000, so the drawdown
    profile has a genuine peak-to-trough to report. The benchmark levels are chosen so the two
    benchmark XIRRs differ from the portfolio's — the excess figures are non-trivial.
    """
    nav = (
        NavPoint(as_of=SIP_1, nav_inr=Decimal("10000")),
        NavPoint(as_of=DEPLOY_DATE, nav_inr=Decimal("10500")),
        NavPoint(as_of=DATA_RED_DATE, nav_inr=Decimal("9800")),
        NavPoint(as_of=SIP_2, nav_inr=Decimal("20800")),
        NavPoint(as_of=AS_OF, nav_inr=Decimal("21500")),
    )
    benchmark = _tri(
        "nifty50_tri",
        "NIFTY 50 TRI",
        {WINDOW_START: "20000", SIP_2: "20800", AS_OF: "21200"},
    )
    theme = _tri(
        "robotics_proxy",
        "Robotics theme proxy",
        {WINDOW_START: "1000", SIP_2: "1010", AS_OF: "1015"},
    )
    return PackValuation(nav_series=nav, benchmark=benchmark, theme=theme)


# ── the paper-run journal (real Journal writes, payloads matching the M5 loop's writers) ──────


def _heartbeat_bundle(trading_date: date) -> EvidenceBundle:
    """A minimal but valid T0 evidence bundle — a heartbeat needs one (invariant #9)."""
    return EvidenceBundle(
        case_id=CASE_ID,
        trading_date=trading_date,
        actor=Actor.T0,
        items=(
            EvidenceItem(
                kind=EvidenceKind.STATUS,
                source="status_api",
                label="sync",
                text="all core datasets PUBLISHED and quality-green",
            ),
        ),
    )


def _write_paper_run(journal: Journal) -> None:
    """Write a faithful paper-run journal for the reference case (acceptance 1's substrate).

    The entries mirror what the M5 daily loop's real writers emit — the payload keys are A7's and
    A8's, verbatim — so the pack reads the production journal shape. Every trading date carries at
    least a heartbeat (invariant #9); the eventful days add the trade, review, block or skip.
    """
    # A heartbeat every session in the window's active range (invariant #9).
    for day in (SIP_1, DEPLOY_DATE, T1_INTACT_DATE, SIP_2, RAIL_BLOCK_DATE, T1_BROKEN_DATE):
        journal.heartbeat(_heartbeat_bundle(day), actor=Actor.T0)

    # SIP instalment #1: parked in the liquid ETF the same session (A7 park payload).
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=SIP_1,
            case_id=CASE_ID,
            actor=Actor.EXEC,
            decision=Decision.BUY,
            isin=PARKING_ISIN,
            sleeve=Sleeve.CASH,
            rationale="parking the SIP instalment in the liquid ETF the same session (§5.6)",
            payload={
                "source_SIP_INSTALMENT": str(SIP_AMOUNT),
                "shares": "10",
                "price": "1000",
                "residual_cash": "0",
            },
        )
    )
    # Tactical deployment of the parked cash (A7 deploy payload).
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=DEPLOY_DATE,
            case_id=CASE_ID,
            actor=Actor.T2,
            decision=Decision.BUY,
            isin=DEPLOY_ISIN,
            sleeve=Sleeve.TACTICAL,
            rationale="deploy the parked SIP instalment on a tactical opportunity (§5.6)",
            payload={"deployed_inr": str(DEPLOY_VALUE), "sleeve": Sleeve.TACTICAL.value},
        )
    )
    # A T1 review that finds the thesis intact — a HOLD carrying its verdict and its token cost.
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=T1_INTACT_DATE,
            case_id=CASE_ID,
            actor=Actor.T1,
            decision=Decision.HOLD,
            isin=INTACT_ISIN,
            model=STUB_MODEL,
            tokens=T1_TOKENS,
            break_conditions_evaluated=(
                BreakConditionEvaluation(
                    id="BC1", verdict=Verdict.INTACT, observed="delivery volumes holding"
                ),
            ),
        )
    )
    # A data-red day: the loop reads /status/sync, finds it not green, and does not trade.
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=DATA_RED_DATE,
            case_id=CASE_ID,
            actor=Actor.SYSTEM,
            decision=Decision.SKIPPED_DATA_RED,
            rationale="bhavcopy did not publish; /status/sync not green, no trading (inv #10)",
        )
    )
    # SIP instalment #2, a month later.
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=SIP_2,
            case_id=CASE_ID,
            actor=Actor.EXEC,
            decision=Decision.BUY,
            isin=PARKING_ISIN,
            sleeve=Sleeve.CASH,
            rationale="parking the second SIP instalment in the liquid ETF (§5.6)",
            payload={
                "source_SIP_INSTALMENT": str(SIP_AMOUNT),
                "shares": "10",
                "price": "1000",
                "residual_cash": "0",
            },
        )
    )
    # An oversized order refused by A8 — a RAIL_BLOCK (rails working, not a breach).
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=RAIL_BLOCK_DATE,
            case_id=CASE_ID,
            actor=Actor.RAILS,
            decision=Decision.RAIL_BLOCK,
            isin=RAIL_ISIN,
            rationale="order value exceeds the ratified per-order cap; refused (invariant #6)",
            payload={"rails": "MAX_ORDER_VALUE"},
        )
    )
    # A T2 review that finds a break condition BROKEN — escalated, with its token cost.
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=T1_BROKEN_DATE,
            case_id=CASE_ID,
            actor=Actor.T2,
            decision=Decision.ESCALATE,
            isin=EXIT_ISIN,
            model=STUB_MODEL,
            tokens=T2_TOKENS,
            rationale="BC2 broken: order book collapsed two quarters running; escalating for exit",
            break_conditions_evaluated=(
                BreakConditionEvaluation(
                    id="BC2", verdict=Verdict.BROKEN, observed="revenue guidance withdrawn"
                ),
            ),
        )
    )
    # The core exit that followed the BROKEN verdict — books a realized gain (a tax event). The
    # value/gain/charges/holding-period keys are what a value-carrying exit records; see the M6.6
    # backlog note on making A6's SELL entries carry these so this is journal-reconstructable.
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=EXIT_DATE,
            case_id=CASE_ID,
            actor=Actor.T2,
            decision=Decision.SELL,
            isin=EXIT_ISIN,
            sleeve=Sleeve.CORE,
            rationale="exit on the BROKEN thesis over the ratified menu (§5.5, decision #4)",
            break_conditions_evaluated=(
                BreakConditionEvaluation(
                    id="BC2", verdict=Verdict.BROKEN, observed="thesis broken"
                ),
            ),
            payload={
                "value_inr": str(EXIT_VALUE),
                "realized_gain_inr": str(EXIT_GAIN),
                "charges_inr": str(EXIT_CHARGES),
                "holding_period": "SHORT",
            },
        )
    )


def _write_breach_case(journal: Journal) -> None:
    """A second case whose journal carries a rail breach that reached the book (acceptance 3).

    One SIP pay-in (so a pack can be generated at all) and one BUY flagged `rail_breach` — a trade
    that violated a cap the rails should have stopped. This is the defect the pack must surface as a
    bug, not a neutral event.
    """
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=SIP_1,
            case_id=BREACH_CASE_ID,
            actor=Actor.EXEC,
            decision=Decision.BUY,
            isin=PARKING_ISIN,
            sleeve=Sleeve.CASH,
            rationale="parking the SIP instalment (§5.6)",
            payload={"source_SIP_INSTALMENT": str(SIP_AMOUNT), "shares": "10", "price": "1000"},
        )
    )
    journal.append(
        JournalEntry(
            ts=RUN_AT,
            trading_date=DEPLOY_DATE,
            case_id=BREACH_CASE_ID,
            actor=Actor.EXEC,
            decision=Decision.BUY,
            isin=DEPLOY_ISIN,
            sleeve=Sleeve.TACTICAL,
            rationale="a position that breached the per-position cap but was filled — a rails bug",
            payload={
                "deployed_inr": "50000",
                "rail_breach": "true",
                "rails": "MAX_POSITION",
            },
        )
    )


# ── database fixtures (the scratch-DB pattern from test_journal.py / test_paper_run) ──────────


def _settings_for(dbname: str) -> Settings:
    return Settings(database_url=with_dbname(Settings().database_url, dbname))


def _insert_case(conn: psycopg.Connection, case_id: str, title: str) -> None:
    """A minimal ACTIVE/PAPER case_ row — decision_journal.case_id is a foreign key onto it."""
    conn.execute(
        "INSERT INTO case_ (case_id, title, state, funding_mode, theme, created_at, updated_at) "
        "VALUES (%s, %s, 'ACTIVE', 'PAPER', %s, %s, %s)",
        (case_id, title, "ai & robotics", RUN_AT, RUN_AT),
    )


@pytest.fixture(scope="session")
def pack_settings(tmp_path_factory: pytest.TempPathFactory) -> Iterator[Settings]:
    """An empty scratch database with the schema applied and the paper-run journal committed."""
    admin = _settings_for("postgres")
    try:
        conn = connect(admin, autocommit=True)
    except psycopg.OperationalError as error:  # pragma: no cover - environment, not logic
        pytest.skip(f"postgres is not reachable — run `make up` first: {error}")
    try:
        conn.execute(f'DROP DATABASE IF EXISTS "{SCRATCH_DB}" WITH (FORCE)')
        conn.execute(f'CREATE DATABASE "{SCRATCH_DB}"')
    finally:
        conn.close()

    scratch = _settings_for(SCRATCH_DB)
    migrate(scratch, clock=FrozenClock(RUN_AT))

    evidence_root = tmp_path_factory.mktemp("pack_evidence")
    with connection(scratch) as conn:
        _insert_case(conn, CASE_ID, "AI & robotics reference case")
        _insert_case(conn, BREACH_CASE_ID, "Rail-breach demonstration case")
        journal = Journal(
            conn, clock=FrozenClock(RUN_AT), evidence=EvidenceStore(root=evidence_root)
        )
        _write_paper_run(journal)
        _write_breach_case(journal)
        conn.commit()

    yield scratch

    conn = connect(admin, autocommit=True)
    try:
        conn.execute(f'DROP DATABASE IF EXISTS "{SCRATCH_DB}" WITH (FORCE)')
    finally:
        conn.close()


