CASE_ID: Final = "ai-robotics-ref"
BREACH_CASE_ID: Final = "breach-demo"

#: The pack window and the sessions the paper run writes into it. Two SIP instalments land inside it
#: (2026-08-03 and 2026-09-01), so the return is struck on two pay-ins plus the terminal NAV mark.
WINDOW_START: Final = date(2026, 8, 1)
WINDOW_END: Final = date(2026, 9, 30)
